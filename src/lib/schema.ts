/**
 * The content contract for this portfolio.
 *
 * This file is the single source of truth. It is used by:
 *   - the site, to load and type content          (src/lib/content.ts)
 *   - `npm run validate`, to check every project  (scripts/validate-content.ts)
 *   - `npm run new:project`, to scaffold one      (scripts/new-project.mjs)
 *
 * If you are an agent adding a project, you do not need to read this file  - 
 * read AGENTS.md, then run `npm run validate` and fix what it tells you.
 */
import { z } from "zod";

/** Media paths are relative to the project's own folder, e.g. "media/cover.webp". */
const MediaPath = z
  .string()
  .regex(
    /^media\/[A-Za-z0-9._-]+\.(webp|jpg|jpeg|png|mp4|webm)$/,
    'must look like "media/name.webp", relative to the project folder, no subfolders',
  );

export const MediaSchema = z.object({
  src: MediaPath,
  kind: z.enum(["image", "video"]),
  /** Poster frame for videos. Generated by `npm run media`. */
  poster: MediaPath.nullable().default(null),
  /** Required on images for accessibility. Describe what is shown, not "screenshot of app". */
  alt: z.string().min(1).nullable().default(null),
  caption: z.string().nullable().default(null),
  /**
   * Videos only. Plays muted and looped while it is on screen and pauses when it
   * scrolls away. Controls stay available, and reduced-motion users get a
   * normal click-to-play video instead.
   */
  autoplay: z.boolean().default(false),
});

/**
 * A simple flow diagram drawn from text, so it reads in light and dark mode and
 * a screen reader gets it as a list. Steps run left to right on a wide screen
 * (top to bottom from five steps, and always on a phone). A step holds one to
 * three boxes side by side.
 */
export const DiagramSchema = z.object({
  /** Read by screen readers before the steps. Say what the diagram shows. */
  label: z.string().min(1),
  caption: z.string().min(1).nullable().default(null),
  steps: z
    .array(
      z.object({
        /** Short text on the arrow that leads into this step. Ignored on the first step. */
        arrow: z.string().min(1).max(40).nullable().default(null),
        nodes: z
          .array(
            z.object({
              title: z.string().min(1).max(40),
              detail: z.string().min(1).max(90).nullable().default(null),
            }),
          )
          .min(1)
          .max(3),
      }),
    )
    .min(2)
    .max(7),
});

export const SectionSchema = z.object({
  heading: z.string().min(1).nullable().default(null),
  /** 3 renders the heading one size down, as a part of the section above it. */
  level: z.union([z.literal(2), z.literal(3)]).default(2),
  /** One string per paragraph. Plain text: no HTML, no markdown. */
  body: z.array(z.string().min(1)).default([]),
  /** Optional bullet points, shown after the paragraphs. Plain text, one string each. */
  bullets: z.array(z.string().min(1)).default([]),
  /** Optional fixed-width blocks for output, code, and alignment-sensitive text. */
  codeBlocks: z.array(z.string().min(1)).default([]),
  /**
   * Desktop relationship between a section's prose and its media. "wide" puts
   * the media in the full page column instead of the reading column: one item
   * at full width, several in two big columns.
   */
  layout: z.enum(["stack", "media-left", "media-right", "wide"]).default("stack"),
  media: z.array(MediaSchema).default([]),
  /** Optional diagram, shown after the text and before the media. */
  diagram: DiagramSchema.nullable().default(null),
});

/**
 * The 30-second version of a project, shown at the top of its page next to the
 * hero: what it is, why I made it, what I did, and how it turned out. One or
 * two plain sentences each, in first person.
 */
export const OverviewSchema = z.object({
  what: z.string().min(1),
  why: z.string().min(1),
  did: z.string().min(1),
  result: z.string().min(1),
});

/**
 * "How it went": a short traction block under the overview of a shipped app
 * (Engine Miles first, November 2026). A three-step timeline, one funnel chart
 * comparing two app versions, a few sentences about the change between them,
 * and one or two lines on what I watch. Every number in it is a fixed fact as
 * of `asOf`; the live totals live in public/stats.json instead.
 */
const FunnelSeriesSchema = z.object({
  /** "Before", "After". Short: it is the legend and the bar label. */
  label: z.string().min(1).max(24),
  /** "1.0, Oct 20 to 26". Shown under the label in the legend. */
  detail: z.string().min(1).max(60),
  /** People at each step, in step order. The first is the 100% everyone else is measured against. */
  counts: z.array(z.number().int().nonnegative()).min(2),
});

export const FunnelSchema = z
  .object({
    title: z.string().min(1).max(80),
    /** Step names, in order. */
    steps: z.array(z.string().min(1).max(32)).min(2).max(6),
    /** Index of the step the story is about. Its row gets a note. */
    focus: z.number().int().nonnegative().nullable().default(null),
    /** Short note beside the focus row, e.g. "Lost here: 43% before, 27% after". */
    focusNote: z.string().min(1).max(80).nullable().default(null),
    /** Exactly two series: the old version (drawn in grey) and the new one (in the app's colour). */
    series: z.tuple([FunnelSeriesSchema, FunnelSeriesSchema]),
    /** Under the chart. Say the sample size honestly. */
    caption: z.string().min(1),
    /** Where the numbers came from. Shown small under the caption. */
    source: z.string().min(1),
  })
  .superRefine((funnel, context) => {
    funnel.series.forEach((series, index) => {
      if (series.counts.length !== funnel.steps.length) {
        context.addIssue({
          code: "custom",
          path: ["series", index, "counts"],
          message: `needs one count per step (${funnel.steps.length})`,
        });
      }
      series.counts.forEach((count, step) => {
        if (step > 0 && count > series.counts[step - 1]) {
          context.addIssue({
            code: "custom",
            path: ["series", index, "counts", step],
            message: "a funnel step can't have more people than the step before it",
          });
        }
      });
    });
    if (funnel.focus !== null && funnel.focus >= funnel.steps.length) {
      context.addIssue({ code: "custom", path: ["focus"], message: "is past the last step" });
    }
  });

export const HowItWentSchema = z.object({
  /** "YYYY-MM-DD" the numbers were checked. Internal, for the next update. */
  asOf: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  timeline: z
    .array(
      z.object({
        /** "Oct 20, 2026". Short. */
        when: z.string().min(1).max(32),
        title: z.string().min(1).max(60),
      }),
    )
    .min(2)
    .max(4),
  /** The fix, in one or two short paragraphs next to the chart. */
  story: z.array(z.string().min(1)).min(1).max(2),
  funnel: FunnelSchema.nullable().default(null),
  /** One line each: what I watch, and how I'm getting it out there. */
  watch: z
    .array(z.object({ label: z.string().min(1).max(24), text: z.string().min(1) }))
    .max(3)
    .default([]),
});

/**
 * public/stats.json: rounded totals per app, written once a day by Social
 * Diffusion from RevenueCat and PostHog. Keyed by project slug. No keys, no
 * revenue, nothing per person: only what the site shows.
 */
export const AppStatsSchema = z.object({
  /** Already rounded down, with a plus: "90+", "10+". */
  users_rounded: z.string().regex(/^\d+\+$/, 'a rounded count like "90+"'),
  /** Paid purchases (subscriptions started plus lifetime), exact. Gifts and promos don't count. */
  sales: z.number().int().nonnegative(),
  /** ISO 8601 date or date-time of the last update. */
  updated_at: z.string().regex(/^\d{4}-\d{2}-\d{2}(T[\d:.]+(Z|[+-]\d{2}:?\d{2})?)?$/),
});

export const StatsFileSchema = z.record(
  z.string().regex(/^[a-z0-9]+(-[a-z0-9]+)*$/, "a project slug"),
  AppStatsSchema,
);

export const LinkSchema = z.object({
  label: z.string().min(1),
  href: z.string().url(),
});

const ProjectDateSchema = z
  .string()
  .regex(/^\d{4}(-(0[1-9]|1[0-2]))?$/, 'use "YYYY" or "YYYY-MM"');

export const ProjectSchema = z.object({
  /** Must equal the folder name. Lowercase kebab-case. */
  slug: z.string().regex(/^[a-z0-9]+(-[a-z0-9]+)*$/, "lowercase-kebab-case only"),
  title: z.string().min(1),
  /** One line, shown on the card. Keep under ~90 characters. */
  tagline: z.string().min(1).max(140),
  /** Two to four sentences. Shown at the top of the detail page when there is no overview. */
  summary: z.string().min(1),
  /** The short top block of the detail page. When it is set, it replaces the summary there. */
  overview: OverviewSchema.nullable().default(null),
  /**
   * Michael's own original page, kept word for word (cryptogram, foosball,
   * symposium). The page shows only his text: the tagline and summary are still
   * used on cards and in search results, but not repeated on the page itself.
   * An overview may sit on top as a separate short summary (cryptogram and
   * foosball have one, November 10); his text follows under "My original
   * write-up", and the word lock in validate-content.ts does not cover it.
   */
  ownWords: z.boolean().default(false),

  /** false hides the project from the site entirely, without deleting it. */
  published: z.boolean().default(false),
  /** Puts the project in "Selected work" on the homepage. Ordering lives in src/lib/project-order.ts. */
  featured: z.boolean().default(false),

  /** Start date. "YYYY" or "YYYY-MM". null sorts after dated work. */
  date: ProjectDateSchema.nullable().default(null),
  /** Optional finish date, or "present" for active work. */
  endDate: z.union([ProjectDateSchema, z.literal("present")]).nullable().default(null),
  status: z.string().nullable().default(null),

  /** How the implementation was produced, not whether the finished product contains AI. */
  development: z.enum(["human-led", "ai-assisted", "ai-generated"]).nullable().default(null),

  /**
   * What it is actually built with. Not file formats it happens to read.
   * Each entry renders as a pill, so it is a label, not a sentence. Put the
   * explanation in a section instead.
   */
  tech: z.array(z.string().min(1).max(40, "a tech entry is a pill label, not a sentence")).default([]),
  links: z.array(LinkSchema).default([]),

  hero: MediaSchema.nullable().default(null),
  /** Optional traction block, shown right under the overview. */
  howItWent: HowItWentSchema.nullable().default(null),
  sections: z.array(SectionSchema).default([]),

  /** Internal. Never rendered. Use it to leave notes for yourself or the next agent. */
  notes: z.string().nullable().default(null),
}).superRefine((project, context) => {
  if (project.endDate !== null && project.date === null) {
    context.addIssue({
      code: "custom",
      path: ["endDate"],
      message: "needs a start date in date",
    });
    return;
  }

  if (
    project.date !== null &&
    project.endDate !== null &&
    project.endDate !== "present" &&
    project.endDate < project.date
  ) {
    context.addIssue({
      code: "custom",
      path: ["endDate"],
      message: "cannot be earlier than date",
    });
  }
});

export const ProfileSchema = z.object({
  name: z.string().min(1),
  headline: z.string().min(1),
  bio: z.string().min(1),
  location: z.string().nullable().default(null),
  email: z.string().email().nullable().default(null),
  resume: z.string().nullable().default(null),
  links: z.array(LinkSchema).default([]),
  /** Long-form "about" copy. One string per paragraph. */
  about: z.array(z.string().min(1)).default([]),
});

/** One job on the Work page. Dates are free text as they read on the resume ("Summer 2026"). */
export const JobSchema = z.object({
  role: z.string().min(1),
  company: z.string().min(1),
  location: z.string().nullable().default(null),
  dates: z.string().min(1),
  /** One or two plain sentences in first person. */
  summary: z.string().min(1),
  /** Short points, one string each. */
  highlights: z.array(z.string().min(1)).default([]),
  /** Slugs of published projects that came out of this job. */
  projects: z.array(z.string().min(1)).default([]),
});

export const EducationSchema = z.object({
  school: z.string().min(1),
  degree: z.string().min(1),
  dates: z.string().min(1),
  details: z.array(z.string().min(1)).default([]),
});

/** content/work.json: the work-experience half of the resume. */
export const WorkSchema = z.object({
  intro: z.string().min(1),
  jobs: z.array(JobSchema).default([]),
  education: z.array(EducationSchema).default([]),
});

export type Media = z.infer<typeof MediaSchema>;
export type Section = z.infer<typeof SectionSchema>;
export type Diagram = z.infer<typeof DiagramSchema>;
export type Overview = z.infer<typeof OverviewSchema>;
export type Link = z.infer<typeof LinkSchema>;
export type HowItWent = z.infer<typeof HowItWentSchema>;
export type Funnel = z.infer<typeof FunnelSchema>;
export type AppStats = z.infer<typeof AppStatsSchema>;
export type StatsFile = z.infer<typeof StatsFileSchema>;
export type Project = z.infer<typeof ProjectSchema>;
export type Profile = z.infer<typeof ProfileSchema>;
export type Job = z.infer<typeof JobSchema>;
export type Work = z.infer<typeof WorkSchema>;

/** Intrinsic image dimensions are read from the media file during content loading. */
export type ResolvedMedia = Media & {
  width?: number;
  height?: number;
};

export type ResolvedSection = Omit<Section, "media"> & {
  media: ResolvedMedia[];
};

/** A project with its media paths rewritten to public URLs (`/media/<slug>/...`). */
export type ResolvedProject = Omit<Project, "hero" | "sections"> & {
  hero: ResolvedMedia | null;
  sections: ResolvedSection[];
};
